/** Local Cloudflare Worker + Durable Object collaboration integration coverage. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import net from 'node:net';

const ROOT = new URL('..', import.meta.url).pathname;
const server = net.createServer();
const port = await new Promise((resolve) => server.listen(0, '127.0.0.1', () => { const value = server.address().port; server.close(() => resolve(value)); }));
const worker = spawn('npx', ['wrangler', 'dev', '--config', 'cloudflare/relay/wrangler.toml', '--port', String(port)], { cwd: ROOT, stdio: 'ignore', detached: process.platform !== 'win32' });
const origin = `http://127.0.0.1:${port}`;
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const waitForMessage = (socket, predicate, timeout = 7000) => new Promise((resolve, reject) => {
  const seen = [];
  const timer = setTimeout(() => { socket.removeEventListener('message', onMessage); reject(new Error(`timed out waiting for relay message; saw ${seen.join(', ')}`)); }, timeout);
  function onMessage(event) {
    let message;
    try { message = JSON.parse(event.data); } catch { return; }
    seen.push(`${message.type}${message.room?.pageView ? ':pageView' : ''}${message.room?.session?.comments?.length ? `:comments=${message.room.session.comments.length}` : ''}`);
    if (!predicate(message)) return;
    clearTimeout(timer); socket.removeEventListener('message', onMessage); resolve(message);
  }
  socket.addEventListener('message', onMessage);
});
const connect = async (roomId, token) => {
  const socket = new WebSocket(`ws://127.0.0.1:${port}/api/rooms/${roomId}/socket`);
  const connected = waitForMessage(socket, (message) => message.type === 'connected');
  await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }); });
  socket.send(JSON.stringify({ type: 'auth', token }));
  await connected;
  return socket;
};

let ownerSocket;
let memberSocket;
try {
  let ready = false;
  for (let attempt = 0; attempt < 80 && !ready; attempt += 1) {
    if (worker.exitCode !== null) throw new Error(`Wrangler exited early (${worker.exitCode})`);
    ready = await fetch(origin).then((response) => response.ok).catch(() => false);
    if (!ready) await pause(250);
  }
  assert.ok(ready, 'Wrangler local relay did not become ready');
  const formPost = await fetch(`${origin}/api/rooms`, { method: 'POST', headers: { 'content-type': 'text/plain' }, body: JSON.stringify({ project: 'e2e' }) });
  assert.equal(formPost.status, 415, 'room creation rejects cross-origin simple form requests');
  const created = await fetch(`${origin}/api/rooms`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ project: 'Relay integration' }) });
  assert.equal(created.status, 201);
  const room = await created.json();
  assert.match(room.inviteUrl, new RegExp(`/room/${room.roomId}#${room.inviteToken}$`));
  assert.equal(typeof room.ownerToken, 'string', 'room creation returns the locally held owner credential');
  const invitePage = await fetch(`${origin}/room/${room.roomId}`);
  assert.equal(invitePage.status, 200);
  const inviteHtml = await invitePage.text();
  assert.match(inviteHtml, /Join this UIDIT review/);
  assert.match(inviteHtml, /HTML snapshot/);
  assert.match(inviteHtml, /setAttribute\('sandbox','allow-same-origin'\)/);
  assert.match(inviteHtml, /Inspect element/);
  assert.match(invitePage.headers.get('content-security-policy'), /frame-src 'self'/);
  const rejected = await fetch(`${origin}/api/rooms/${room.roomId}/join`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Reviewer', inviteToken: 'invalid' }) });
  assert.equal(rejected.status, 401, 'invalid invite tokens are rejected');
  const joined = await fetch(`${origin}/api/rooms/${room.roomId}/join`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Reviewer', inviteToken: room.inviteToken }) });
  assert.equal(joined.status, 200);
  const member = await joined.json();
  ownerSocket = await connect(room.roomId, room.ownerToken);
  memberSocket = await connect(room.roomId, member.memberToken);
  const pageViewSnapshot = waitForMessage(memberSocket, (message) => message.type === 'snapshot' && message.room.pageView?.width === 1280);
  const deniedPageView = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ dataUrl: 'data:image/jpeg;base64,/9j/2Q==', width: 1280, height: 800 }) });
  assert.equal(deniedPageView.status, 401, 'only the project owner can publish the shared page view');
  const sharedPageView = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { method: 'POST', headers: { authorization: `Bearer ${room.ownerToken}`, 'content-type': 'application/json' }, body: JSON.stringify({ dataUrl: 'data:image/jpeg;base64,/9j/2Q==', width: 1280, height: 800, url: 'http://127.0.0.1:4321/' }) });
  assert.equal(sharedPageView.status, 200);
  assert.equal((await pageViewSnapshot).room.pageView.url, 'http://127.0.0.1:4321/');
  const pageImage = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { headers: { authorization: `Bearer ${member.memberToken}` } });
  assert.equal(pageImage.status, 200, 'joined reviewers can fetch the shared page snapshot');
  assert.match((await pageImage.json()).dataUrl, /^data:image\/jpeg;base64,/);
  const ownerCannotFetchImage = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { headers: { authorization: `Bearer ${room.ownerToken}` } });
  assert.equal(ownerCannotFetchImage.status, 401, 'page image fetches require an authenticated reviewer session');
  const htmlSnapshot = '<!doctype html><html><body><main>Reviewable project page</main></body></html>';
  const htmlViewSnapshot = waitForMessage(memberSocket, (message) => message.type === 'snapshot' && message.room.pageView?.kind === 'html');
  const htmlView = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { method: 'POST', headers: { authorization: `Bearer ${room.ownerToken}`, 'content-type': 'application/json' }, body: JSON.stringify({ html: htmlSnapshot, width: 1280, height: 800, url: 'http://127.0.0.1:4321/cart' }) });
  assert.equal(htmlView.status, 200);
  assert.equal((await htmlView.json()).pageView.kind, 'html');
  assert.equal((await htmlViewSnapshot).room.pageView.url, 'http://127.0.0.1:4321/cart');
  const htmlPage = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { headers: { authorization: `Bearer ${member.memberToken}` } });
  assert.equal((await htmlPage.json()).html, htmlSnapshot, 'joined reviewers can fetch the HTML snapshot');
  const tunnelView = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { method: 'POST', headers: { authorization: `Bearer ${room.ownerToken}`, 'content-type': 'application/json' }, body: JSON.stringify({ liveUrl: 'https://preview-smoke.trycloudflare.com/', width: 1280, height: 800 }) });
  assert.equal(tunnelView.status, 400, 'shared page snapshots no longer publish tunnel URLs');
  const cursor = waitForMessage(ownerSocket, (message) => message.type === 'cursor');
  memberSocket.send(JSON.stringify({ type: 'cursor', x: 1.4, y: -0.2 }));
  const cursorEvent = await cursor;
  assert.equal(cursorEvent.x, 1);
  assert.equal(cursorEvent.y, 0);
  const snapshot = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && message.room.session.comments?.some((comment) => comment.text === 'Please adjust the card spacing.'));
  memberSocket.send(JSON.stringify({ type: 'comment:add', text: 'Please adjust the card spacing.', page: '/', point: { x: 0.25, y: 0.7 }, selector: 'main > h1' }));
  const shared = await snapshot;
  const comment = shared.room.session.comments.find((item) => item.text === 'Please adjust the card spacing.');
  assert.equal(comment.author, 'Reviewer');
  assert.deepEqual(comment.point, { x: 0.25, y: 0.7 }, 'reviewers can pin feedback to a shared page view');
  assert.equal(comment.selector, 'main > h1', 'reviewers can attach feedback to an inspected element');
  assert.ok(shared.room.participants.some((item) => item.role === 'owner'));
  const replySnapshot = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && message.room.session.comments.find((item) => item.id === comment.id)?.replies?.length === 1);
  memberSocket.send(JSON.stringify({ type: 'comment:reply', commentId: comment.id, text: 'I will update it.' }));
  await replySnapshot;
  memberSocket.send(JSON.stringify({ type: 'comment:update', commentId: comment.id, status: 'in_progress', assignee: 'Reviewer' }));
  const readonlySnapshot = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && message.room.session.comments.find((item) => item.id === comment.id)?.replies?.length === 2);
  memberSocket.send(JSON.stringify({ type: 'comment:reply', commentId: comment.id, text: 'Still comment-only.' }));
  const readonly = await readonlySnapshot;
  assert.equal(readonly.room.session.comments.find((item) => item.id === comment.id)?.status, 'open', 'remote reviewers cannot change workflow status');
  assert.equal(readonly.room.session.comments.find((item) => item.id === comment.id)?.assignee, undefined, 'remote reviewers cannot assign comments');
  const ownerSync = waitForMessage(memberSocket, (message) => message.type === 'snapshot' && message.room.session.elements?.some((item) => item.id === 'el-test'));
  ownerSocket.send(JSON.stringify({ type: 'sync', session: { version: 1, revision: 4, updatedAt: new Date().toISOString(), elements: [{ id: 'el-test', selector: '#checkout', text: 'private page content', attributes: { 'data-secret': 'private' } }], edits: [{ id: 'edit-test', before: 'private source content', after: 'changed content' }], comments: [{ id: 'cm-image', source: 'collaborator', author: 'Reviewer', text: 'Use this photo as a reference', attachments: [{ name: 'reference.jpg', mimeType: 'image/jpeg', dataUrl: 'data:image/jpeg;base64,/9j/2Q==' }] }, { id: 'cm-owner', source: 'owner', author: 'Project owner', text: 'Keep this owner note.' }] } }));
  const sharedImage = await ownerSync;
  assert.equal(sharedImage.room.session.comments.find((item) => item.id === 'cm-image').attachments[0].name, 'reference.jpg');
  assert.deepEqual(sharedImage.room.session.elements, [{ id: 'el-test', selector: '#checkout' }], 'shared snapshots omit page text and attributes');
  assert.deepEqual(sharedImage.room.session.edits, [], 'shared snapshots omit local edits');
  const unauthorizedDelete = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && message.room.session.comments.find((item) => item.id === comment.id)?.replies?.length === 3);
  memberSocket.send(JSON.stringify({ type: 'comment:delete', commentId: 'cm-owner' }));
  memberSocket.send(JSON.stringify({ type: 'comment:reply', commentId: comment.id, text: 'Deletion of another review note was ignored.' }));
  const stillPresent = await unauthorizedDelete;
  assert.ok(stillPresent.room.session.comments.some((item) => item.id === 'cm-owner'), 'reviewers cannot delete the project owner’s comment');
  const deleted = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && !message.room.session.comments.some((item) => item.id === comment.id) && message.room.session.deletedCommentIds?.includes(comment.id));
  memberSocket.send(JSON.stringify({ type: 'comment:delete', commentId: comment.id }));
  const deletion = await deleted;
  assert.ok(deletion.room.session.deletedCommentIds.includes(comment.id), 'comment deletion syncs a tombstone so it does not return on owner refresh');
  const ownerDeletion = waitForMessage(memberSocket, (message) => message.type === 'snapshot' && !message.room.session.comments.some((item) => item.id === 'cm-owner') && message.room.session.deletedCommentIds?.includes('cm-owner'));
  ownerSocket.send(JSON.stringify({ type: 'sync', session: { ...deletion.room.session, comments: [...deletion.room.session.comments, { id: 'cm-owner', source: 'owner', text: 'Owner note deleted locally.' }], deletedCommentIds: ['cm-owner'] } }));
  const ownerDeletionSnapshot = await ownerDeletion;
  assert.ok(ownerDeletionSnapshot.room.session.deletedCommentIds.includes('cm-owner'), 'local owner deletions sync tombstones and cannot be restored by the room');
  const legacyDelete = waitForMessage(ownerSocket, (message) => message.type === 'snapshot' && !message.room.session.comments.some((item) => item.id === 'cm-image') && message.room.session.deletedCommentIds?.includes('cm-image'));
  memberSocket.send(JSON.stringify({ type: 'comment:delete', commentId: 'cm-image' }));
  await legacyDelete;
  const expiredInvite = await fetch(`${origin}/api/rooms/${room.roomId}/revoke-invite`, { method: 'POST' });
  assert.equal(expiredInvite.status, 401, 'invite revocation requires the owner token');
  const closed = new Promise((resolve) => memberSocket.addEventListener('close', resolve, { once: true }));
  const revoked = await fetch(`${origin}/api/rooms/${room.roomId}/revoke-invite`, { method: 'POST', headers: { authorization: `Bearer ${room.ownerToken}` } });
  assert.equal(revoked.status, 200);
  const rotated = await revoked.json();
  assert.ok(Date.parse(rotated.inviteExpiresAt) > Date.now());
  await closed;
  const oldLink = await fetch(`${origin}/api/rooms/${room.roomId}/join`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Late reviewer', inviteToken: room.inviteToken }) });
  assert.equal(oldLink.status, 401, 'rotating a link revokes the previous invite');
  const newLink = await fetch(`${origin}/api/rooms/${room.roomId}/join`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'New reviewer', inviteToken: rotated.inviteToken }) });
  assert.equal(newLink.status, 200, 'the replacement invite remains usable');
  const newMember = await newLink.json();
  memberSocket = await connect(room.roomId, newMember.memberToken);
  const ownerClosed = new Promise((resolve) => ownerSocket.addEventListener('close', resolve, { once: true }));
  const memberClosed = new Promise((resolve) => memberSocket.addEventListener('close', resolve, { once: true }));
  const unauthorizedStop = await fetch(`${origin}/api/rooms/${room.roomId}`, { method: 'DELETE' });
  assert.equal(unauthorizedStop.status, 401, 'stopping a room requires the owner token');
  const stopped = await fetch(`${origin}/api/rooms/${room.roomId}`, { method: 'DELETE', headers: { authorization: `Bearer ${room.ownerToken}` } });
  assert.equal(stopped.status, 200);
  assert.deepEqual(await stopped.json(), { closed: true });
  await Promise.all([ownerClosed, memberClosed]);
  const stoppedInvite = await fetch(`${origin}/api/rooms/${room.roomId}/join`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'After stop', inviteToken: rotated.inviteToken }) });
  assert.equal(stoppedInvite.status, 404, 'stopping sharing permanently removes the room and invalidates every invite');
  const removedPageView = await fetch(`${origin}/api/rooms/${room.roomId}/page-view`, { headers: { authorization: `Bearer ${newMember.memberToken}` } });
  assert.equal(removedPageView.status, 404, 'stopping sharing removes the shared page snapshot');
  console.log('  ok  secret-free share creation, page snapshots and pins, comment/reply/delete permissions, invite rotation and complete room shutdown');
} finally {
  ownerSocket?.close(); memberSocket?.close();
  try { if (process.platform !== 'win32' && worker.pid) process.kill(-worker.pid, 'SIGTERM'); else worker.kill('SIGTERM'); } catch {}
  await new Promise((resolve) => { if (worker.exitCode !== null) resolve(); else { worker.once('exit', resolve); setTimeout(resolve, 2000).unref(); } });
}
